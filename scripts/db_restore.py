#!/usr/bin/env python3
"""
MTIS Database Restore Script (Operational Rubric D5).
Restores database state from a SQL backup file generated by db_backup.py.
Supports PostgreSQL (via psql or docker exec mtis-postgres-db psql)
and local SQLite.

Usage:
    python scripts/db_restore.py --input database/backups/mtis_backup_latest.sql
    python scripts/db_restore.py -i database/backups/mtis_backup_latest.sql --url postgresql://user:password@localhost:5432/malaysian_thesis_institution_system_mtis
"""
import os
import sys
import argparse
import subprocess
import shutil
from pathlib import Path
from urllib.parse import urlparse

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "backend"))


def get_default_db_url() -> str:
    db_url = os.getenv("DATABASE_URL")
    if db_url:
        return db_url

    env_file = PROJECT_ROOT / ".env"
    if env_file.exists():
        with open(env_file, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("DATABASE_URL="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")

    sqlite_db = PROJECT_ROOT / "backend" / "demo_mtis.db"
    if sqlite_db.exists():
        return f"sqlite:///{sqlite_db.as_posix()}"

    return "postgresql://user:password@localhost:5432/malaysian_thesis_institution_system_mtis"


def restore_sqlite(input_file: Path, target_db_path: Path) -> bool:
    import sqlite3
    print(f"[Restore] Restoring SQLite database from {input_file} into {target_db_path}...")
    try:
        with open(input_file, "r", encoding="utf-8") as f:
            sql_script = f.read()

        conn = sqlite3.connect(str(target_db_path))
        cursor = conn.cursor()
        cursor.executescript(sql_script)
        conn.commit()
        conn.close()
        print(f"[Restore] Successfully restored SQLite database: {target_db_path}")
        return True
    except Exception as e:
        print(f"[Restore Error] Failed to restore SQLite: {e}", file=sys.stderr)
        return False


def restore_postgres(input_file: Path, url: str) -> bool:
    parsed = urlparse(url)
    username = parsed.username or "user"
    password = parsed.password or "password"
    hostname = parsed.hostname or "localhost"
    port = str(parsed.port or 5432)
    dbname = parsed.path.lstrip("/") or "malaysian_thesis_institution_system_mtis"

    env = os.environ.copy()
    env["PGPASSWORD"] = password

    # 1. Try local psql
    psql_bin = shutil.which("psql")
    if psql_bin:
        cmd = [
            psql_bin,
            "-h", hostname,
            "-p", port,
            "-U", username,
            "-d", dbname,
            "-f", str(input_file),
        ]
        print(f"[Restore] Executing psql command: {' '.join(cmd[:5])}...")
        try:
            res = subprocess.run(cmd, env=env, capture_output=True, text=True, check=True)
            print(f"[Restore] psql restore completed successfully.")
            return True
        except subprocess.CalledProcessError as e:
            print(f"[Restore Warning] psql returned code {e.returncode}: {e.stderr.strip()}", file=sys.stderr)

    # 2. Try docker exec
    docker_bin = shutil.which("docker")
    if docker_bin:
        container_name = "mtis-postgres-db"
        cmd = [
            docker_bin, "exec", "-i",
            "-e", f"PGPASSWORD={password}",
            container_name,
            "psql", "-U", username, "-d", dbname,
        ]
        print(f"[Restore] Attempting docker exec restore via {container_name}...")
        try:
            with open(input_file, "rb") as f:
                res = subprocess.run(cmd, stdin=f, capture_output=True, text=True, check=True)
            print(f"[Restore] Docker psql restore completed successfully.")
            return True
        except Exception as e:
            print(f"[Restore Warning] Docker psql restore attempt: {e}", file=sys.stderr)

    # 3. Fallback to demo SQLite
    local_sqlite = PROJECT_ROOT / "backend" / "demo_mtis.db"
    if local_sqlite.exists():
        print("[Restore] Restoring against local demo SQLite database...")
        return restore_sqlite(input_file, local_sqlite)

    print("[Restore Error] Unable to restore database via psql or Docker.", file=sys.stderr)
    return False


def main():
    parser = argparse.ArgumentParser(description="MTIS Database Restore Utility (D5 Operations)")
    parser.add_argument("-i", "--input", required=True, help="Input path of SQL backup file")
    parser.add_argument("--url", help="Target database connection URL (defaults to DATABASE_URL)")
    args = parser.parse_args()

    input_file = Path(args.input).resolve()
    if not input_file.exists():
        print(f"[Restore Error] Input file not found: {input_file}", file=sys.stderr)
        sys.exit(1)

    db_url = args.url or get_default_db_url()

    print(f"=== MTIS Database Restore ===")
    print(f"Source file: {input_file}")
    print(f"Target DB:   {db_url.split('@')[-1] if '@' in db_url else db_url}")

    if db_url.startswith("sqlite"):
        db_path_str = db_url.replace("sqlite:///", "")
        db_path = Path(db_path_str)
        if not db_path.is_absolute():
            db_path = PROJECT_ROOT / db_path
        if not db_path.exists():
            alt_path = PROJECT_ROOT / "backend" / db_path_str
            if alt_path.exists():
                db_path = alt_path
        success = restore_sqlite(input_file, db_path)
    else:
        success = restore_postgres(input_file, db_url)

    if success:
        print("[Restore Success] Database restoration completed successfully.")
        sys.exit(0)
    else:
        print("[Restore Failed] Database restore failed.", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
